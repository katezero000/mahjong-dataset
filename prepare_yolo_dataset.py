"""
Prepare the Mahjong dataset in YOLO format for object detection training.

This script converts the existing classification dataset into a YOLO-compatible
directory structure with bounding-box annotations.  Because every source image
contains exactly one tile that fills the frame, the bounding box is set to the
full image (cx=0.5, cy=0.5, w=1.0, h=1.0) and the class index is derived from
the label column in data.csv (converted from 1-based to 0-based).

Output layout
--------------
yolo_dataset/
    images/
        train/   *.jpg
        val/     *.jpg
    labels/
        train/   *.txt
        val/     *.txt
    dataset.yaml

Usage
-----
    python prepare_yolo_dataset.py [--val-split 0.2] [--seed 42]
              [--images-dir tiles-resized] [--csv tiles-data/data.csv]
              [--output yolo_dataset]
"""

import argparse
import csv
import os
import random
import shutil


CLASSES = [
    "dots-1", "dots-2", "dots-3", "dots-4", "dots-5",
    "dots-6", "dots-7", "dots-8", "dots-9",
    "bamboo-1", "bamboo-2", "bamboo-3", "bamboo-4", "bamboo-5",
    "bamboo-6", "bamboo-7", "bamboo-8", "bamboo-9",
    "characters-1", "characters-2", "characters-3", "characters-4",
    "characters-5", "characters-6", "characters-7", "characters-8",
    "characters-9",
    "honors-east", "honors-south", "honors-west", "honors-north",
    "honors-red", "honors-green", "honors-white",
    "bonus-spring", "bonus-summer", "bonus-autumn", "bonus-winter",
    "bonus-plum", "bonus-orchid", "bonus-chrysanthemum", "bonus-bamboo",
]

YAML_TEMPLATE = """\
# Mahjong tile detection dataset – YOLO format
# Generated by prepare_yolo_dataset.py

path: {output_dir}
train: images/train
val:   images/val

nc: {nc}
names: {names}
"""


def parse_args():
    parser = argparse.ArgumentParser(description="Convert Mahjong dataset to YOLO format")
    parser.add_argument("--val-split", type=float, default=0.2,
                        help="Fraction of images to use for validation (default: 0.2)")
    parser.add_argument("--seed", type=int, default=42,
                        help="Random seed for reproducible splits (default: 42)")
    parser.add_argument("--images-dir", default="tiles-resized",
                        help="Directory containing source images (default: tiles-resized)")
    parser.add_argument("--csv", default="tiles-data/data.csv",
                        help="CSV file with image labels (default: tiles-data/data.csv)")
    parser.add_argument("--output", default="yolo_dataset",
                        help="Output directory (default: yolo_dataset)")
    return parser.parse_args()


def read_labels(csv_path):
    """Return a list of (image_name, class_id) tuples from data.csv (0-indexed)."""
    entries = []
    seen = set()
    with open(csv_path, newline="", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        for row in reader:
            name = row["image-name"].strip()
            label = int(row["label"].strip())
            if name in seen:
                continue  # skip duplicates
            seen.add(name)
            entries.append((name, label - 1))  # convert to 0-based
    return entries


def make_dirs(output):
    for split in ("train", "val"):
        os.makedirs(os.path.join(output, "images", split), exist_ok=True)
        os.makedirs(os.path.join(output, "labels", split), exist_ok=True)


def write_label(label_path, class_id):
    """Write a YOLO annotation file for a full-image bounding box."""
    with open(label_path, "w") as f:
        f.write(f"{class_id} 0.5 0.5 1.0 1.0\n")


def write_yaml(output, yaml_content):
    yaml_path = os.path.join(output, "dataset.yaml")
    with open(yaml_path, "w") as f:
        f.write(yaml_content)
    return yaml_path


def main():
    args = parse_args()

    repo_root = os.path.dirname(os.path.abspath(__file__))
    images_dir = os.path.join(repo_root, args.images_dir)
    csv_path = os.path.join(repo_root, args.csv)
    output = os.path.join(repo_root, args.output)

    if not os.path.isdir(images_dir):
        raise FileNotFoundError(f"Images directory not found: {images_dir}")
    if not os.path.isfile(csv_path):
        raise FileNotFoundError(f"CSV file not found: {csv_path}")

    entries = read_labels(csv_path)

    # Keep only entries whose image file actually exists
    available = [(name, cid) for name, cid in entries
                 if os.path.isfile(os.path.join(images_dir, name))]
    missing = len(entries) - len(available)
    if missing:
        print(f"Warning: {missing} image(s) listed in CSV were not found and will be skipped.")

    random.seed(args.seed)
    random.shuffle(available)

    n_val = max(1, int(len(available) * args.val_split))
    val_set = available[:n_val]
    train_set = available[n_val:]

    make_dirs(output)

    for split, data in (("train", train_set), ("val", val_set)):
        for name, class_id in data:
            src_img = os.path.join(images_dir, name)
            dst_img = os.path.join(output, "images", split, name)
            shutil.copy2(src_img, dst_img)

            stem = os.path.splitext(name)[0]
            lbl_path = os.path.join(output, "labels", split, stem + ".txt")
            write_label(lbl_path, class_id)

    abs_output = os.path.abspath(output)
    yaml_content = YAML_TEMPLATE.format(
        output_dir=abs_output,
        nc=len(CLASSES),
        names=CLASSES,
    )
    yaml_path = write_yaml(output, yaml_content)

    print(f"Dataset prepared in: {abs_output}")
    print(f"  Train images : {len(train_set)}")
    print(f"  Val images   : {len(val_set)}")
    print(f"  Classes      : {len(CLASSES)}")
    print(f"  YAML config  : {yaml_path}")
    print()
    print("To train with Ultralytics YOLOv8:")
    print(f"  pip install ultralytics")
    print(f"  yolo detect train data={yaml_path} model=yolov8n.pt epochs=100 imgsz=320")


if __name__ == "__main__":
    main()
